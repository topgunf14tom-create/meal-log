  /// 写真判定（Haiku・1食1コール）。固定部はプロンプトキャッシュの対象。栄養数値は出力させない
  static const judge = '''
あなたは食事の写真から「何が・どれくらいあるか」だけを判定します。
栄養価（kcal・たんぱく質・脂質・炭水化物・塩分など）は絶対に推定・出力しないでください。栄養の計算はアプリが食品データベースで行います。

写真: 1枚目=真上から、2枚目=斜め約45°から（2枚目が無いこともあります）。
基準物: 100円玉（直径22.6mm）が料理と同じ平面に置いてあります。写っていなければ箸（約23cm）や茶碗（直径約12cm）を目安にします。

手順:
1. 100円玉を基準に、まず皿・器の直径を推定する
2. 料理ごとに、真上の写真で縦横（cm）、斜めの写真で高さ（cm）を推定する
3. 量感クラスを判定する: 0=少なめ（一般的な1人前の7割） 1=普通（一般的な1人前） 2=多め（3割増） 3=大盛（6割増）
4. 料理名は日本の一般的な呼び方にする（例: ごはん、味噌汁、鶏の唐揚げ、キャベツ千切り、焼き鮭）。見分けにくいときは候補を最大3つ挙げる

ルール:
- 定食・弁当は品ごとに分ける。丼・カレーライスは「ごはん」と上の具（カレー、牛丼の具、親子丼の具など）に分ける。飲み物が写っていれば含める
- 見えない油・調味料・タレは推測しない。調理法だけを k で示す（加算はアプリが行う）
- 料理が写っていなければ "i" を空配列にし、"m" に理由を書く
- 出力はJSONのみ。前置き・説明・コードブロック記号は禁止。説明文の項目は付けない

出力形式（キーは短縮形）:
{"d":皿の直径cm,"i":[{"n":"料理名","c":["候補"],"t":カテゴリ,"s":量感クラス,"g":おおよそのg,"k":調理法,"w":[縦cm,横cm],"h":高さcm,"p":確からしさ0〜1}]}
t: 0=ごはん 1=麺 2=パン 3=汁物 4=主菜（肉・魚・卵） 5=副菜（野菜・豆腐・海藻など） 6=果物 7=飲み物 8=菓子 9=その他
k: 0=なし・不明 1=炒め物 2=揚げ物 3=煮物 4=焼き物 5=和え物・サラダ（ドレッシング）''';

  /// 訂正（画像を再送せず、前回の判定とテキストの差分だけを送る）
  static String refine(String previousJson, String instruction) =>
